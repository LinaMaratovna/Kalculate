import kotlin.math.abs // Импортируем функцию модуля (абсолютного значения) для проверок
import kotlin.math.pow // Импортируем функцию возведения в степень для бинарной операции степени

object Calculator { // Объявляем объект (синглтон) Calculator, хранящий математические операции
    // Бинарная операция сложения: принимает два операнда (x и y) и возвращает их сумму
    fun plus(x: Double, y: Double) = x + y
    // Бинарная операция вычитания: принимает два операнда (x и y) и возвращает их разность
    fun minus(x: Double, y: Double) = x - y
    // Бинарная операция умножения: принимает два операнда (x и y) и возвращает их произведение
    fun umnoshite(x: Double, y: Double) = x * y

    // Бинарная операция деления: принимает два операнда (делимое x и делитель y)
    fun delenie(x: Double, y: Double): Double {
        if (y == 0.0) { // Проверяем второй операнд (y) на равенство нулю, чтобы избежать ошибки
            throw ArithmeticException("Делить на ноль нельзя!") // Выбрасываем исключение при делении на ноль
        } // Конец блока проверки делителя
        return x / y // Возвращаем результат бинарной операции деления x на y
    } // Конец функции деления

    // Унарная операция извлечения корня: принимает один операнд (x)
    fun korene(x: Double): Double {
        if (x < 0) { // Проверяем единственный операнд (x) на отрицательность
            throw ArithmeticException("Отрицательный корень!") // Выбрасываем исключение для отрицательного числа
        } // Конец блока проверки операнда
        return kotlin.math.sqrt(x) // Возвращаем результат унарной операции (квадратный корень из x)
    } // Конец функции корня

    // Бинарная операция возведения в степень: принимает основание (x) и показатель (y)
    fun stepene(x: Double, y: Double) = x.pow(y)

    // Унарная функция синуса: принимает один операнд (угол в градусах), преобразует в радианы и вычисляет синус
    fun sinus(deg: Double) = kotlin.math.sin(Math.toRadians(deg))
    // Унарная функция косинуса: принимает один операнд (угол в градусах), преобразует в радианы и вычисляет косинус
    fun cosinus(deg: Double) = kotlin.math.cos(Math.toRadians(deg))

    // Унарная функция тангенса: принимает один операнд (угол в градусах)
    fun tangens(deg: Double): Double {
        val normalized = ((deg % 180.0) + 180.0) % 180.0 // Нормализуем угол к диапазону [0, 180) для корректной проверки
        if (abs(normalized - 90.0) < 1e-12) { // Проверяем, не равен ли угол 90 градусам (где тангенс не определен)
            throw ArithmeticException("Тангенс не определён для угла $deg°") // Выбрасываем исключение
        } // Конец блока проверки угла
        return kotlin.math.tan(Math.toRadians(deg)) // Возвращаем результат унарной операции (тангенс угла)
    } // Конец функции тангенса

    // Унарная функция десятичного логарифма: принимает один операнд (x)
    fun log10(x: Double): Double {
        if (x <= 0.0) { // Проверяем единственный операнд (x) на неположительность
            throw ArithmeticException("Логарифм от числа меньше или равного нулю!") // Выбрасываем исключение
        } // Конец блока проверки операнда
        return kotlin.math.log10(x) // Возвращаем результат унарной операции (log10 от x)
    } // Конец функции log10

    // Унарная функция натурального логарифма: принимает один операнд (x)
    fun ln(x: Double): Double {
        if (x <= 0.0) { // Проверяем единственный операнд (x) на неположительность
            throw ArithmeticException("Логарифм от числа меньше или равного нулю!") // Выбрасываем исключение
        } // Конец блока проверки операнда
        return kotlin.math.ln(x) // Возвращаем результат унарной операции (ln от x)
    } // Конец функции ln
} // Конец объекта Calculator

class ExpressionParser(private val input: String) { // Объявляем класс парсера с приватным полем input (входная строка)
    private var pos = 0 // Объявляем приватную переменную pos для отслеживания текущей позиции (индекса) в строке

    fun parse(): Double { // Публичная функция парсинга, возвращающая итоговый результат типа Double
        val result = parseExpression() // Вызываем метод парсинга выражения (низший приоритет) и сохраняем результат
        skipWhitespace() // Пропускаем любые пробельные символы в конце строки после вычислений
        if (pos < input.length) { // Проверяем, остались ли непрочитанные символы после полного парсинга
            throw IllegalArgumentException("Неожиданный символ '${input[pos]}' на позиции $pos") // Выбрасываем исключение, если строка разобрана не полностью
        } // Конец блока проверки остатка строки
        return result // Возвращаем итоговый вычисленный результат
    } // Конец функции parse

    private fun skipWhitespace() { // Приватная функция для пропуска пробельных символов
        while (pos < input.length && input[pos].isWhitespace()) { // Пока не конец строки и текущий символ является пробелом
            pos++ // Увеличиваем индекс позиции на 1, перешагивая через пробел
        } // Конец цикла while
    } // Конец функции skipWhitespace

    // 1. Сложение и вычитание (низший приоритет) - БИНАРНЫЕ операции
    private fun parseExpression(): Double { // Функция парсинга бинарных операций сложения и вычитания
        var result = parseTerm() // Сначала парсим операнд более высокого приоритета (умножение/деление)
        while (true) { // Бесконечный цикл для обработки цепочки бинарных операций сложения/вычитания
            skipWhitespace() // Пропускаем пробелы перед возможным бинарным оператором
            if (pos >= input.length) break // Если достигли конца строки, прерываем цикл
            result = when (input[pos]) { // Проверяем текущий символ на соответствие бинарному оператору
                '+' -> { // Если это бинарный оператор сложения
                    pos++ // Сдвигаем позицию на 1, чтобы пропустить символ '+'
                    Calculator.plus(result, parseTerm()) // Выполняем бинарную операцию: предыдущий результат + новый терм
                } // Конец ветки '+'
                '-' -> { // Если это бинарный оператор вычитания
                    pos++ // Сдвигаем позицию на 1, чтобы пропустить символ '-'
                    Calculator.minus(result, parseTerm()) // Выполняем бинарную операцию: предыдущий результат - новый терм
                } // Конец ветки '-'
                else -> break // Если символ не '+' и не '-', прерываем цикл (это не бинарный оператор сложения/вычитания)
            } // Конец выражения when
        } // Конец цикла while
        return result // Возвращаем результат вычисления выражения
    } // Конец функции parseExpression

    // 2. Умножение и деление - БИНАРНЫЕ операции среднего приоритета
    private fun parseTerm(): Double { // Функция парсинга бинарных операций умножения и деления
        var result = parsePower() // Сначала парсим операнд более высокого приоритета (возведение в степень)
        while (true) { // Бесконечный цикл для обработки цепочки бинарных операций умножения/деления
            skipWhitespace() // Пропускаем пробелы перед возможным бинарным оператором
            if (pos >= input.length) break // Если достигли конца строки, прерываем цикл
            result = when (input[pos]) { // Проверяем текущий символ на соответствие бинарному оператору
                '*' -> { // Если это бинарный оператор умножения
                    pos++ // Сдвигаем позицию на 1, чтобы пропустить символ '*'
                    Calculator.umnoshite(result, parsePower()) // Выполняем бинарную операцию: предыдущий результат * новая степень
                } // Конец ветки '*'
                '/' -> { // Если это бинарный оператор деления
                    pos++ // Сдвигаем позицию на 1, чтобы пропустить символ '/'
                    Calculator.delenie(result, parsePower()) // Выполняем бинарную операцию: предыдущий результат / новая степень
                } // Конец ветки '/'
                else -> break // Если символ не '*' и не '/', прерываем цикл
            } // Конец выражения when
        } // Конец цикла while
        return result // Возвращаем результат вычисления терма
    } // Конец функции parseTerm

    // 3. Возведение в степень (правоассоциативное: 2^3^2 = 2^(3^2)) - БИНАРНАЯ операция высокого приоритета
    private fun parsePower(): Double { // Функция парсинга бинарной операции возведения в степень
        val base = parseUnary() // Сначала парсим унарный операнд (основание степени)
        skipWhitespace() // Пропускаем пробелы перед оператором степени
        if (pos < input.length && input[pos] == '^') { // Если текущий символ - это бинарный оператор возведения в степень
            pos++ // Сдвигаем позицию на 1, чтобы пропустить символ '^'
            return Calculator.stepene(base, parsePower()) // Рекурсивно вызываем parsePower для правой ассоциативности бинарной операции
        } // Конец блока if
        return base // Если оператора '^' нет, возвращаем просто основание (как унарный или первичный операнд)
    } // Конец функции parsePower

    // 4. Унарный плюс и минус - УНАРНЫЕ операции
    private fun parseUnary(): Double { // Функция парсинга унарных операций (знак перед одним операндом)
        skipWhitespace() // Пропускаем пробелы перед возможным унарным оператором
        if (pos < input.length) { // Проверяем, что не достигли конца строки
            when (input[pos]) { // Проверяем текущий символ на унарный оператор
                '+' -> { // Если это унарный плюс (один операнд, знак не меняет)
                    pos++ // Сдвигаем позицию на 1
                    return parseUnary() // Рекурсивно обрабатываем следующий унарный оператор или операнд
                } // Конец ветки '+'
                '-' -> { // Если это унарный минус (инвертирует знак одного операнда)
                    pos++ // Сдвигаем позицию на 1
                    return -parseUnary() // Рекурсивно обрабатываем и инвертируем знак результата (унарная операция отрицания)
                } // Конец ветки '-'
            } // Конец выражения when
        } // Конец блока if
        return parsePrimary() // Если унарных операторов нет, переходим к парсингу первичных операндов (числа, скобки, функции)
    } // Конец функции parseUnary

    // 5. Числа, скобки, константы и функции (первичные операнды для унарных/бинарных операций)
    private fun parsePrimary(): Double { // Функция парсинга первичных элементов выражения
        skipWhitespace() // Пропускаем пробелы перед первичным элементом
        if (pos >= input.length) { // Проверяем, не достигли ли мы конца строки неожиданно
            throw IllegalArgumentException("Неожиданный конец выражения") // Выбрасываем исключение
        } // Конец блока проверки

        // Скобки (группировка любых бинарных/унарных операций)
        if (input[pos] == '(') { // Если текущий символ - открывающая скобка
            pos++ // Сдвигаем позицию на 1, пропуская '('
            val value = parseExpression() // Рекурсивно парсим выражение внутри скобок (может содержать любые операции)
            skipWhitespace() // Пропускаем пробелы перед закрывающей скобкой
            if (pos >= input.length || input[pos] != ')') { // Проверяем наличие закрывающей скобки
                throw IllegalArgumentException("Ожидалась закрывающая скобка ')'") // Выбрасываем исключение, если скобки нет
            } // Конец блока проверки
            pos++ // Сдвигаем позицию на 1, пропуская ')'
            return value // Возвращаем вычисленное значение в скобках как единый операнд
        } // Конец блока обработки скобок

        // Числа (целые и дробные) - первичные операнды
        if (input[pos].isDigit() || input[pos] == '.' || input[pos] == ',') { // Если текущий символ - цифра или разделитель дроби
            val start = pos // Запоминаем начальную позицию числа
            while (pos < input.length && (input[pos].isDigit() || input[pos] == '.' || input[pos] == ',')) { // Собираем все символы числа
                pos++ // Увеличиваем позицию
            } // Конец цикла while
            val numStr = input.substring(start, pos).replace(',', '.') // Извлекаем подстроку числа и заменяем запятую на точку
            return numStr.toDoubleOrNull() // Пытаемся преобразовать строку в число типа Double
                ?: throw IllegalArgumentException("Некорректное число: $numStr") // Если не удалось, выбрасываем исключение
        } // Конец блока обработки чисел

        // Имена функций (унарные операции) и констант
        if (input[pos].isLetter()) { // Если текущий символ - буква (начало имени функции или константы)
            val start = pos // Запоминаем начальную позицию имени
            while (pos < input.length && input[pos].isLetter()) { // Собираем все буквы имени
                pos++ // Увеличиваем позицию
            } // Конец цикла while
            val name = input.substring(start, pos).lowercase() // Извлекаем имя и приводим к нижнему регистру

            when (name) { // Проверяем, является ли имя математической константой
                "pi" -> return kotlin.math.PI // Если "pi", возвращаем значение числа Пи (первичный операнд)
                "e" -> return kotlin.math.E // Если "e", возвращаем значение числа Эйлера (первичный операнд)
            } // Конец выражения when для констант

            // Поддержка записи как sin(30), так и sin30 (унарные функции)
            skipWhitespace() // Пропускаем пробелы между именем функции и аргументом
            val arg = if (pos < input.length && input[pos] == '(') { // Если после имени есть открывающая скобка
                pos++ // Сдвигаем позицию, пропуская '('
                val inner = parseExpression() // Парсим выражение внутри скобок как аргумент унарной функции
                skipWhitespace() // Пропускаем пробелы перед закрывающей скобкой
                if (pos >= input.length || input[pos] != ')') { // Проверяем наличие закрывающей скобки
                    throw IllegalArgumentException("Ожидалась ')' после аргумента функции $name") // Выбрасываем исключение
                } // Конец блока проверки
                pos++ // Сдвигаем позицию, пропуская ')'
                inner // Возвращаем вычисленный аргумент
            } else { // Если скобок нет (например, sin30)
                parseUnary() // Парсим следующий унарный оператор или первичный операнд как аргумент функции
            } // Конец блока if-else для аргумента

            return when (name) { // Применяем унарную функцию к вычисленному аргументу (arg)
                "sqrt" -> Calculator.korene(arg) // Унарная операция: квадратный корень из arg
                "sin" -> Calculator.sinus(arg) // Унарная операция: синус от arg
                "cos" -> Calculator.cosinus(arg) // Унарная операция: косинус от arg
                "tan" -> Calculator.tangens(arg) // Унарная операция: тангенс от arg
                "log" -> Calculator.log10(arg) // Унарная операция: десятичный логарифм от arg
                "ln" -> Calculator.ln(arg) // Унарная операция: натуральный логарифм от arg
                else -> throw IllegalArgumentException("Неизвестная функция: $name") // Выбрасываем исключение для неизвестной функции
            } // Конец выражения when для функций
        } // Конец блока обработки имен

        throw IllegalArgumentException("Неожиданный символ '${input[pos]}'") // Выбрасываем исключение, если символ не распознан
    } // Конец функции parsePrimary
} // Конец класса ExpressionParser

fun vichislenie(primer: String): Double { // Функция вычисления, принимающая строку примера
    if (primer.isBlank()) { // Проверяем, не является ли строка пустой или состоящей только из пробелов
        throw IllegalArgumentException("Пустой ввод") // Выбрасываем исключение при пустом вводе
    } // Конец блока проверки
    return ExpressionParser(primer).parse() // Создаем парсер и запускаем парсинг, возвращая результат (Double)
} // Конец функции vichislenie

fun main() { // Точка входа в программу (главная функция)
    println("Инженерный калькулятор.") // Выводим приветственное сообщение в консоль
    println("Функции: sin, cos, tan, sqrt, log, ln | Константы: pi, e") // Выводим информацию о поддерживаемых функциях и константах
    println("Примеры: (2+2)*2*cos30, sqrt(16) + tan45, log100 + ln(e)") // Выводим примеры корректного ввода (с бинарными и унарными операциями)
    println("Для выхода введите: exit\n") // Выводим инструкцию по выходу из программы

    while (true) { // Бесконечный цикл для непрерывного приема ввода от пользователя
        val primer = readLine() ?: break // Считываем строку из консоли, если null (конец потока), прерываем цикл

        if (primer.trim().lowercase() == "exit") { // Проверяем, не ввел ли пользователь команду "exit" (с удалением пробелов и в нижнем регистре)
            break // Прерываем цикл, если введено "exit"
        } // Конец блока проверки

        try { // Начинаем блок обработки исключений (попытка выполнить код)
            val result = vichislenie(primer) // Вызываем функцию вычисления переданного примера
            println("= $result") // Выводим результат вычисления в консоль
        } catch (e: Exception) { // Если в процессе вычисления произошло исключение (ошибка)
            println("Ошибка: ${e.message}") // Выводим сообщение об ошибке в консоль
        } // Конец блока try-catch
    } // Конец цикла while
    println("Завершение работы...") // Выводим сообщение о завершении работы программы после выхода из цикла
} // Конец функции main